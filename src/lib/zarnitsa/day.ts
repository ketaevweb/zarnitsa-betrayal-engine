/** утренняя реплика по эху прошлой ночи (M1.2).
 *  day — номер дня (2/3): строка stable, не мигает между кадрами. */
export function echoLine(
  cid: string,
  echo: { cid: string; spared: boolean; tag: TagId }[] | undefined,
  day: number,
): EchoLine {
  const hit = echo?.find((e) => e.cid === cid);
  if (hit && !hit.spared) {
    const text = ECHO_SCORNED[cid]?.[hit.tag] ?? ECHO_SCORNED_ANY[cid] ?? "";
    if (text) return { text, tone: "scorned" };
  }
  if (hit && hit.spared && ECHO_SPARED[cid]) return { text: ECHO_SPARED[cid]!, tone: "spared" };
  const pool = ECHO_IDLE[cid] ?? [];
  if (pool.length === 0) return { text: "", tone: "idle" };
  let h = day * 31;
  for (let i = 0; i < cid.length; i++) h = (h * 7 + cid.charCodeAt(i)) % 9973;
  return { text: pool[h % pool.length]!, tone: "idle" };
}
